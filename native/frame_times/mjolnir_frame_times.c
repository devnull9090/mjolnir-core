/* Where each value's instruction sits in the pattern. */
enum {
    AT_SECONDS_PER_CYCLE = 0x000, /* vmovsd xmm3, [rip+d]   C5 FB 10 1D d32 */
    AT_GAME = 0x043,              /* mov eax, [rip+d]       8B 05 d32 */
    AT_GAME_CP = 0x094,
    AT_DRAW = 0x0c7,
    AT_DRAW_CP = 0x108,
    AT_RHIT = 0x18c,
    AT_DYNAMIC_RHI = 0x28b,       /* mov rcx, [rip+d]       48 8B 0D d32 */
    AT_GPU_SLOT = 0x297,          /* call [rax+slot]        FF 90 s32 */
};

typedef unsigned(__fastcall *gpu_cycles_t)(void *rhi, unsigned gpu_index);

static int resolved; /* 0 not tried, 1 found, -1 not found */
static char why[160];
static const unsigned *g_game, *g_game_cp, *g_draw, *g_draw_cp, *g_rhit;
static void *const *g_dynamic_rhi;
static const double *g_seconds_per_cycle;
static unsigned gpu_slot;
static char dir[MAX_PATH];

enum { N = 6 };
static double sum[N];
static unsigned frames;

static void find_dir(void) {
    HMODULE self = NULL;
    GetModuleHandleExA(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,
                       (LPCSTR)&find_dir, &self);
    GetModuleFileNameA(self, dir, sizeof dir);
    char *slash = strrchr(dir, '\\');
    if (slash) slash[1] = 0;
}

static const void *rip(const unsigned char *ins, int disp_at, int len) {
    int d;
    memcpy(&d, ins + disp_at, 4);
    return ins + len + d;
}

static int matches(const unsigned char *p) {
    for (size_t i = 0; i < sizeof pattern / sizeof pattern[0]; i++)
        if (pattern[i] >= 0 && p[i] != (unsigned char)pattern[i]) return 0;
    return 1;
}

static void resolve(void) {
    if (resolved) return;
    resolved = -1;
    const unsigned char *base = (const unsigned char *)GetModuleHandleW(NULL);
    const IMAGE_DOS_HEADER *dos = (const IMAGE_DOS_HEADER *)base;
    const IMAGE_NT_HEADERS64 *nt = (const IMAGE_NT_HEADERS64 *)(base + dos->e_lfanew);
    const IMAGE_SECTION_HEADER *sec = IMAGE_FIRST_SECTION(nt);
    const unsigned char *text = NULL;
    size_t size = 0;
    for (unsigned i = 0; i < nt->FileHeader.NumberOfSections; i++) {
        if (memcmp(sec[i].Name, ".text", 6) == 0) {
            text = base + sec[i].VirtualAddress;
            size = sec[i].Misc.VirtualSize;
        }
    }
    const size_t n = sizeof pattern / sizeof pattern[0];
    if (!text || size < n) {
        snprintf(why, sizeof why, "no .text section");
        return;
    }
    const unsigned char *found = NULL;
    int count = 0;
    for (const unsigned char *p = text, *end = text + size - n; p <= end; p++) {
        p = memchr(p, pattern[0], (size_t)(end - p) + 1);
        if (!p) break;
        if (matches(p)) {
            found = p;
            if (++count > 1) break;
        }
    }
    if (count != 1) {
        snprintf(why, sizeof why, "stat unit's DrawStat %s (game updated?)", count ? "matched twice" : "not found");
        return;
    }
    g_seconds_per_cycle = rip(found + AT_SECONDS_PER_CYCLE, 4, 8);
    g_game = rip(found + AT_GAME, 2, 6);
    g_game_cp = rip(found + AT_GAME_CP, 2, 6);
    g_draw = rip(found + AT_DRAW, 2, 6);
    g_draw_cp = rip(found + AT_DRAW_CP, 2, 6);
    g_rhit = rip(found + AT_RHIT, 2, 6);
    g_dynamic_rhi = rip(found + AT_DYNAMIC_RHI, 3, 7);
    memcpy(&gpu_slot, found + AT_GPU_SLOT + 2, 4);
    if (gpu_slot % 8 || gpu_slot > 0x2000) {
        snprintf(why, sizeof why, "odd RHI slot 0x%x", gpu_slot);
        return;
    }
    resolved = 1;
}

/* The last frame's figures in milliseconds; 0 when the RHI was not there. */
static int read_frame(double out[N]) {
    __try {
        const double ms = *g_seconds_per_cycle * 1000.0;
        if (!(ms > 0)) return 0;
        out[0] = *g_game * ms;
        out[1] = *g_game_cp * ms;
        out[2] = *g_draw * ms;
        out[3] = *g_draw_cp * ms;
        out[4] = *g_rhit * ms;
        void *rhi = *g_dynamic_rhi;
        if (!rhi) return 0;
        gpu_cycles_t gpu = *(gpu_cycles_t *)(*(const unsigned char *const *)rhi + gpu_slot);
        out[5] = gpu(rhi, 0) * ms;
        return 1;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        return 0;
    }
}

__declspec(dllexport) int mjolnir_frame_times_sample(void *L) {
    (void)L;
    resolve();
    if (resolved != 1) return 0;
    double f[N];
    if (!read_frame(f)) return 0;
    for (int i = 0; i < N; i++) sum[i] += f[i];
    frames++;
    return 0;
}

__declspec(dllexport) int mjolnir_frame_times_flush(void *L) {
    (void)L;
    resolve();
    if (!dir[0]) find_dir();
    char path[MAX_PATH];
    snprintf(path, sizeof path, "%sframe_times.txt", dir);
    FILE *f = fopen(path, "w");
    if (f) {
        if (resolved != 1) {
            fprintf(f, "error %s\n", why);
        } else {
            fprintf(f, "ok %u", frames);
            for (int i = 0; i < N; i++) fprintf(f, " %.3f", frames ? sum[i] / frames : 0.0);
            fprintf(f, "\n");
        }
        fclose(f);
    }
    memset(sum, 0, sizeof sum);
    frames = 0;
    return 0;
}
