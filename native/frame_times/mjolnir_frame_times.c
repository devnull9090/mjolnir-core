/*
 * MJOLNIR frame times: `stat unit`'s Game, Draw, RHIT and GPU, for Lua.
 *
 * A bench (MJOLNIRHud Scripts/bench.lua) times whole frames, which says what a
 * change costs but not where: a frame is as slow as the slowest of the game
 * thread, the render thread and the GPU. `stat unit` names that one, and it
 * works in this Shipping build, but it only draws its numbers; nothing
 * reflected holds them. They are engine globals, cycle counts written each
 * frame, which FStatUnitData::DrawStat reads:
 *
 *     GGameThreadTime, GGameThreadTimeCriticalPath,
 *     GRenderThreadTime, GRenderThreadTimeCriticalPath, GRHIThreadTime,
 *     GDynamicRHI->RHIGetGPUFrameCycles(0)
 *
 * and turns into milliseconds with FPlatformTime::SecondsPerCycle. This finds
 * DrawStat's opening by a byte pattern (the exe's .text, refused unless it
 * matches exactly once) and decodes those addresses from its RIP-relative
 * loads at run time; no displacement is baked in, so an update that only moves
 * data still resolves (docs/performance.md, "Where a frame goes"). After a
 * game update, tools/pe/statunit_pattern.py checks the pattern against the
 * new exe and, if it no longer matches, finds DrawStat again and prints a new
 * one with its offsets.
 *
 * Game here includes the game thread's wait for the GPU, as stat unit's does
 * in this build; the critical-path figures leave waits out.
 *
 * Lua has no C API here (UE4SS does not export it), so the calls take no
 * arguments and answer in a file:
 *
 *   package.loadlib(dll, "mjolnir_frame_times_sample")  every frame: adds the
 *       last frame's figures to a running sum.
 *   package.loadlib(dll, "mjolnir_frame_times_flush")   writes the means since
 *       the last flush to native\frame_times.txt and starts a new sum:
 *
 *       ok <frames> <game> <game_cp> <draw> <draw_cp> <rhit> <gpu>
 *
 *   in milliseconds, or `error <why>` when DrawStat was not found. The first
 *   call of either finds it (one scan of .text, a few hundred milliseconds).
 *
 * Both run on the game thread, inside the Lua call.
 */
