"""Sample PWR's cooked landscape source for the native insertion altimeter."""
import hashlib
import json
from pathlib import Path

import numpy as np


HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[1] / "levels/warfare/pwr/terrain/runtime-v5/runtime-master.json"
STEP = 16


def main():
    meta = json.loads(SOURCE.read_text())
    source = SOURCE.parent / meta["height"]["path"]
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if digest != meta["height"]["sha256"] or meta["row_order"] != "+y":
        raise ValueError("PWR heightfield does not match its declared grid")
    height = np.load(source, allow_pickle=False) * meta["height"]["scale_m"] + meta["height"]["offset_m"]
    if height.shape != (1009, 1009) or not np.isfinite(height).all():
        raise ValueError("Expected the 1009-square PWR terrain")
    # Coarse nodes estimate the HUD reading. The highest source vertex in each
    # cell bounds both native collision triangles, including sharp ridge crests.
    cells = (height.shape[0] - 1) // STEP
    roof = [[np.ceil(height[j*STEP:(j+1)*STEP+1, i*STEP:(i+1)*STEP+1].max())
             for i in range(cells)] for j in range(cells)]
    result = [f"/* Generated by generate_warfare_flight_terrain.py, source SHA-256 {digest}. */",
              "#pragma once", f"#define WF_TERRAIN_CELLS {cells}",
              f"#define WF_TERRAIN_X0 {meta['origin_m'][0]:.6f}f",
              f"#define WF_TERRAIN_Y0 {meta['origin_m'][1]:.6f}f",
              f"#define WF_TERRAIN_STEP {STEP * meta['spacing_m'][0]:.7f}f"]
    assert meta['spacing_m'][0] == meta['spacing_m'][1]
    for name, table in [("surface", np.rint(height[::STEP, ::STEP])), ("ceiling", roof)]:
        result.append(f"static const short wf_terrain_{name}[{len(table)}][{len(table[0])}] = {{")
        result.extend("    {" + ",".join(str(int(cell)) for cell in row) + "}," for row in table)
        result.append("};")
    (HERE / "warfare_flight_terrain.h").write_text("\n".join(result) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
