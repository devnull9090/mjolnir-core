"""Generate native PWR constants from the map's authoritative layout manifest."""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "levels/warfare/pwr/layout.json"
HEADER = Path(__file__).with_name("warfare_layout.h")


def vector(value, label):
    if not isinstance(value, list) or len(value) != 3:
        raise ValueError(f"{label} must contain three coordinates")
    if any(isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) for v in value):
        raise ValueError(f"{label} must be finite")
    return [float(v) for v in value]


def marker_points(data):
    markers = []
    for team in ("red", "blue"):
        for side in ("start", "end"):
            markers.append((team+"_flight_"+side, vector(data["flights_m"][team][side], "flight")))
    for team in ("red", "blue"):
        point = vector(data["homes_m"][team], "home"); point[2] += 1.2
        markers.append((team+"_home", point))
    point = vector(data["warmup_m"], "warmup"); point[2] += .8
    markers.append(("warmup", point))
    if len(data["captures_m"]) != 3:
        raise ValueError("Exactly three capture markers are required")
    for label, value in zip("abc", data["captures_m"]):
        point = vector(value, "capture"); point[2] += 1.2
        markers.append(("capture_"+label, point))
    return markers


def validate(data):
    if data.get("schema") != "pwr-layout-v3" or data.get("code") != "PWR":
        raise ValueError("unsupported PWR layout schema")
    for key in ("protocol", "layout_revision"):
        value = data.get(key)
        if isinstance(value, bool) or not isinstance(value, int) or not 1 <= value <= 32767:
            raise ValueError(f"invalid {key}")
    if (data["protocol"], data["layout_revision"]) != (20569, 3):
        raise ValueError("PWR layout3 requires protocol20569")
    if vector(data["coordinates"]["origin_m"], "origin") != [0, 0, 0]:
        raise ValueError("PWR requires the authored zero origin")
    bounds = {}
    for name in ("play_area_m", "scenario_bounds_m"):
        low, high = (vector(data[name][side], name + "." + side) for side in ("min", "max"))
        if any(not low[i] < high[i] or max(abs(low[i]), abs(high[i])) >= 50000 for i in range(3)):
            raise ValueError(f"invalid {name}")
        bounds[name] = (low, high)
    play, shell = bounds["play_area_m"], bounds["scenario_bounds_m"]
    if any(play[0][i] < shell[0][i] or play[1][i] > shell[1][i] for i in range(3)):
        raise ValueError("play area must be inside the scenario")
    duration = float(data["insertion_seconds"])
    forced = float(data["forced_exit_seconds"])
    timeout = float(data["descent_timeout_seconds"])
    if not all(math.isfinite(v) for v in (duration, forced, timeout)) or not (1 <= duration <= 500 and 0 < forced < duration and 5 <= timeout <= 300):
        raise ValueError("invalid flight/drop timing")
    points = []
    for team in ("red", "blue"):
        route = data["flights_m"][team]
        start, end = (vector(route[side], team + "." + side) for side in ("start", "end"))
        if math.dist(start, end) < 1 or math.dist(start, end) / duration > 30:
            raise ValueError("route must be nonempty and fit the 30m/s transport limit")
        for point in (start, end):
            if any(not play[0][i] < point[i] < play[1][i] for i in range(3)):
                raise ValueError("flight endpoints must be strictly inside the play volume")
            points.append(point)
        if timeout < (max(start[2], end[2]) - play[0][2]) / 6 + 10:
            raise ValueError("descent timeout lacks clearance for the lowest floor")
    if len({tuple(v) for v in points}) != 4:
        raise ValueError("four distinct flight flags are required by the runtime map guard")
    markers = marker_points(data)
    if len({tuple(point) for _, point in markers}) != len(markers):
        raise ValueError("Baked gameplay marker positions must be distinct")
    for name, point in markers:
        if any(not play[0][i] < point[i] < play[1][i] for i in range(3)):
            raise ValueError(name + " marker is outside the play volume")
    return data


def generate(data):
    validate(data)
    canonical = json.dumps(data, sort_keys=True, separators=(",", ":")).encode()
    sha = hashlib.sha256(canonical).hexdigest()
    def number(v):
        text = format(float(v), ".9g")
        return text + ("f" if "." in text or "e" in text else ".0f")
    def vec(v):
        return "{" + ", ".join(number(n) for n in v) + "}"
    lines = [
        "/* GENERATED by native/lobby/generate_warfare_layout.py from",
        " * levels/warfare/pwr/layout.json. Do not hand-edit coordinates. */",
        "#ifndef MJOLNIR_WARFARE_LAYOUT_H", "#define MJOLNIR_WARFARE_LAYOUT_H",
        f"#define WARFARE_MAGIC {data['protocol']}",
        f"#define WARFARE_LAYOUT_REVISION {data['layout_revision']}",
        f'#define WARFARE_LAYOUT_SHA256 "{sha}"',
        "#define WARFARE_METRES_PER_WU 3.048f",
        f"#define WARFARE_INSERTION_SECONDS {number(data['insertion_seconds'])}",
        f"#define WARFARE_FORCED_EXIT_SECONDS {number(data['forced_exit_seconds'])}",
        f"#define WARFARE_DESCENT_TIMEOUT_SECONDS {number(data['descent_timeout_seconds'])}",
        "#define WARFARE_TRANSPORT_MAX_SPEED 30.0f",
        "#define WARFARE_ROUTE_CORRECTION_GAIN 0.5f",
        "#define WARFARE_ROUTE_CORRECTION_LIMIT 3.0f",
        "#define WARFARE_TRANSPORT_CLEANUP_SECONDS 5.0f",
    ]
    extent = max(abs(v) for side in data["scenario_bounds_m"].values() for v in side)
    lines.append(f"#define WARFARE_POSITION_SANITY_M {number(extent + 1000)}")
    for kind, key in (("play", "play_area_m"), ("scenario", "scenario_bounds_m")):
        for side in ("min", "max"):
            lines.append(f"static const float warfare_{kind}_{side}[3] = {vec(data[key][side])};")
    lines += ["typedef struct { float start[3], end[3]; } warfare_route;",
              "static const warfare_route warfare_routes[2] = {"]
    for team in ("red", "blue"):
        route = data["flights_m"][team]
        lines.append("    {" + vec(route["start"]) + ", " + vec(route["end"]) + "},")
    markers = marker_points(data)
    lines += ["};", f"#define WARFARE_LAYOUT_MARKERS {len(markers)}",
              "#define WARFARE_LAYOUT_MARKER_MASK ((1u << WARFARE_LAYOUT_MARKERS) - 1u)",
              "static const float warfare_layout_markers[WARFARE_LAYOUT_MARKERS][3] = {"]
    for name, point in markers:
        lines.append("    " + vec(point) + ", /* " + name + " */")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=MANIFEST)
    parser.add_argument("--out", type=Path, default=HEADER)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(json.loads(args.manifest.read_text(encoding="utf-8-sig")))
    existing = args.out.read_text() if args.out.exists() else None
    if args.check:
        if existing != result:
            raise SystemExit("Native Warfare layout is stale; regenerate it from layout.json")
    elif existing != result:
        args.out.write_text(result, encoding="utf-8", newline="\n")
    print("Warfare native layout:", "verified" if args.check else "generated", args.out)


if __name__ == "__main__":
    main()
