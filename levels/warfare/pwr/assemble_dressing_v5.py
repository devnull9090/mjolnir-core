"""Merge reviewed v5 scenery with the frozen Forerunner architecture.

Rock/trunk collision is generated by the regular scenery path. Architecture
collision is supplied once by the measured terrain-extra tail.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools/level"))
from heightfield import load_heightfield, sha256
from b30_collision import material_for


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rocks', type=Path, default=ROOT / 'out/pwr/visual-v5/outcrops-v3/rocks-and-outcrops.authored-decor.json')
    parser.add_argument('--baseline', type=Path, default=ROOT / 'out/pwr/visual-v5/outcrops-v2/rocks-and-outcrops.authored-decor.json')
    parser.add_argument('--expected-rocks', type=int, default=804)
    parser.add_argument('--paving', type=Path, default=ROOT / 'out/pwr/visual-v5/base-paving-v3/footprints.geojson')
    parser.add_argument('--out', type=Path, default=ROOT / 'out/pwr/world-v5/authored-decor.json')
    args = parser.parse_args()
    terrain = load_heightfield(ROOT / "levels/warfare/pwr/terrain/runtime-v5/runtime-master.json")
    layout = ROOT / "levels/warfare/pwr/layout.json"
    geometry = (terrain.path.parent / terrain.metadata["geometry"]).resolve()
    paths = {
        "baseline_decor": ROOT / "out/pwr/pcg-v3/authored-decor.json",
        "rocks": args.rocks.resolve(),
        "rocks_baseline": args.baseline.resolve(),
        "base_details": ROOT / "out/pwr/visual-v4/base-details/authored-decor.json",
    }
    inputs = {key: json.loads(path.read_text()) for key, path in paths.items()}
    details = inputs["base_details"]
    for key, value in {"layout_sha256": sha256(layout), "geometry_sha256": sha256(geometry)}.items():
        if details["provenance"][key] != value:
            raise ValueError("Base-detail placements no longer match frozen " + key)
    rock_proof = inputs["rocks"].get("visual_v4_provenance", {})
    if rock_proof.get("frozen_runtime_master_sha256") != terrain.manifest_sha256:
        raise ValueError("Dressing was generated against another terrain")
    structures = [item for item in inputs["baseline_decor"]["decor"]
                  if "_stock_buttress_" in item["id"]]
    if len(structures) != 9 or len(details["decor"]) != 60:
        raise ValueError("Frozen architecture instance count changed")
    architecture = structures + details["decor"]
    baseline = inputs["rocks_baseline"]["decor"]
    if not baseline or args.expected_rocks < len(baseline) or len(inputs["rocks"]["decor"]) != args.expected_rocks:
        raise ValueError("Reviewed scenery must preserve the supplied baseline and match the explicit expected rock count")
    if inputs["rocks"]["decor"][:len(baseline)] != baseline:
        raise ValueError("Existing reviewed rocks changed during cliff assembly")
    if rock_proof.get("source_rocks_sha256") != sha256(paths["rocks_baseline"]):
        raise ValueError("New cliff assembly does not identify the reviewed source rocks")
    paving = args.paving.resolve()
    if rock_proof.get("paving_sha256") != sha256(paving):
        raise ValueError("Cliff exclusions use a different base-court footprint")
    if any(material_for(item["mesh"]) for item in architecture):
        raise ValueError("Architecture would receive duplicate scenery collision")
    decor = architecture + inputs["rocks"]["decor"]
    if len({item["id"] for item in decor}) != len(decor):
        raise ValueError("Duplicate decoration identifiers")
    document = {
        "schema_version": 1, "coordinates": "unreal_centimetres", "decor": decor,
        "provenance": {
            "runtime_master_sha256": terrain.manifest_sha256,
            "geometry_sha256": sha256(geometry), "layout_sha256": sha256(layout),
            "sources": {key: {"path": str(path), "sha256": sha256(path)}
                        for key, path in paths.items()},
            "architecture_collision": "8336 triangles supplied by terrain-extra; excluded from scenery hull generation",
        },
    }
    output = args.out.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(document, indent=2) + "\n")
    print(json.dumps({"output": str(output), "structures": len(architecture),
                      "rocks": len(inputs["rocks"]["decor"]), "total": len(decor)}))


if __name__ == "__main__":
    main()
