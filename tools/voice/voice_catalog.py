"""Write MJOLNIRHud's catalogue of Warfare voice waves from pick_takes.py's manifest.

  python voice_catalog.py <wave dir>/manifest.tsv [--out mods/MJOLNIRHud/Scripts/warfare_voice_lines.lua]

A wave is <voice>_<event>_<letter> (cortana_auto_chute_b, announcer_zone_lost_c).
warfare_voice.lua asks for a zone line by its full name (zone_lost_c: one wave)
and for any other line by its event (auto_chute: every variant, one picked at
random), so each wave is listed under both. Lengths come from the manifest:
the HUD cannot ask a playing sound when it ends, and the queue needs to know.
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "..", "mods", "MJOLNIRHud", "Scripts", "warfare_voice_lines.lua")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest")
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args()
    table = {}
    for row in open(a.manifest, encoding="utf-8").read().splitlines()[1:]:
        wave, seconds, _ = row.split("\t", 2)
        m = re.match(r"^(cortana|announcer)_(.+)_([a-z])$", wave)
        if not m:
            raise SystemExit(f"{wave}: not <voice>_<event>_<letter>")
        for key in (f"{m.group(2)}_{m.group(3)}", m.group(2)):
            table.setdefault(key, []).append((wave, float(seconds)))
    lines = ["-- Generated by tools/voice/voice_catalog.py from the picked takes' manifest: do not edit.",
             "-- event -> { { wave, seconds }, ... } (warfare_voice.lua).", "return {"]
    for key in sorted(table):
        waves = ", ".join(f'{{ "{w}", {s:.2f} }}' for w, s in sorted(table[key]))
        lines.append(f"    {key} = {{ {waves} }},")
    lines.append("}")
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(table)} keys -> {a.out}")


if __name__ == "__main__":
    main()
